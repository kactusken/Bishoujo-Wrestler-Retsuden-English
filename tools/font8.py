CHARS = [' '] + [chr(c) for c in range(0x21, 0x7F)] + ['…', '♥', '♪']
CODES = {ch: i for i, ch in enumerate(CHARS)}   # code = position: space 0, '!' 1, ... '~' 0x5E


def parse():
    glyphs = {}
    lines = [s for s in _ART.strip('\n').splitlines()]
    for i in range(0, len(lines), 2):
        ch = eval(lines[i])
        rows = lines[i + 1].split('|')
        if len(rows) != 12:
            raise ValueError(f'{ch!r}: {len(rows)} rows')
        glyphs[ch] = rows
    return glyphs


def glyph_bytes():
    """16 bytes per code, in code order; characters without art (backslash, ^, `, {, |, }) blank."""
    g = parse()
    out = bytearray()
    for ch in CHARS:
        rows = [''] * ROW0 + g.get(ch, ['......'] * 12) + [''] * (16 - ROW0 - 12)
        for r in rows:
            b = 0
            for x, c in enumerate(r[:8]):
                if c == '#':
                    b |= 0x80 >> x
            out.append(b)
    return bytes(out)


def sheet(path, text=None):
    from PIL import Image
    data = glyph_bytes()
    text = text or ''.join(CHARS)
    cols = 32
    rows = (len(text) + cols - 1) // cols
    im = Image.new('L', (cols * 8, rows * 16), 40)
    for i, ch in enumerate(text):
        c = CODES.get(ch, 0)
        for y in range(16):
            b = data[c * 16 + y]
            for x in range(8):
                if b & (0x80 >> x):
                    im.putpixel(((i % cols) * 8 + x, (i // cols) * 16 + y), 255)
    im.resize((im.width * 4, im.height * 4), Image.NEAREST).save(path)


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) >= 2 and argv[0] == 'sheet':
        sheet(argv[1], argv[2] if len(argv) > 2 else None)
    else:
        sys.exit(__doc__)


if __name__ == '__main__':
    main()
